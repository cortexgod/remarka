def _normalize_type(meeting_type: str | None) -> str:
    mt = str(meeting_type or "other").strip().lower()
    return mt if mt in MEETING_TYPES else "other"


def _fallback(topic: str, meeting_type: str) -> dict[str, Any]:
    return {
        "topic": topic,
        "meeting_type": meeting_type,
        "checklist": list(_FALLBACK_CHECKLIST.get(meeting_type, _FALLBACK_CHECKLIST["other"]))[:CHECKLIST_MAX],
        "likely_questions": [dict(q) for q in _FALLBACK_QUESTIONS.get(meeting_type, _FALLBACK_QUESTIONS["other"])][:QUESTIONS_N],
        "backend": "none",
    }


def prepare_meeting(
    topic: str,
    meeting_type: str,
    client: LlmClient,
    strict: bool = False,
) -> dict[str, Any]:
    """``PrepResult`` по теме и типу встречи.

    ``strict=True`` — ошибка модели пробрасывается ``LlmError``; иначе статический чеклист (``backend: "none"``).
    """
    topic = " ".join(str(topic or "").split()) or "встреча без темы"
    mt = _normalize_type(meeting_type)
    if client is None or client.backend == "none":
        return _fallback(topic, mt)

    user = render_prompt(
        load_prompt("prepare_user"),
        profile_block=profile_text(),
        topic=topic,
        meeting_type=f"{mt} ({MEETING_TYPE_LABELS.get(mt, mt)})",
        type_hint=TYPE_HINTS.get(mt, TYPE_HINTS["other"]),
        checklist_min=CHECKLIST_MIN,
        checklist_max=CHECKLIST_MAX,
        questions_n=QUESTIONS_N,
    )
    try:
        out = client.complete_json(load_prompt("prepare_system"), user, PrepLlmOutput)
    except LlmError as exc:
        if strict:
            raise
        log(f"prepare: модель недоступна, статический чеклист: {exc}", "warn")
        return _fallback(topic, mt)

    fallback = _fallback(topic, mt)
    checklist: list[str] = []
    for item in out.checklist:
        s = " ".join(str(item or "").split())
        if s and s not in checklist:
            checklist.append(s)
    for item in fallback["checklist"]:
        if len(checklist) >= CHECKLIST_MIN:
            break
        if item not in checklist:
            checklist.append(item)
    questions: list[dict[str, str]] = []
    for q in out.likely_questions:
        if q.question.strip():
            questions.append({"question": q.question.strip(), "why": q.why.strip(), "how_to_prepare": q.how_to_prepare.strip()})
    for q in fallback["likely_questions"]:
        if len(questions) >= QUESTIONS_N:
            break
        questions.append(q)
    return {
        "topic": topic,
        "meeting_type": mt,
        "checklist": checklist[:CHECKLIST_MAX],
        "likely_questions": questions[:QUESTIONS_N],
        "backend": client.backend,
    }
